"use client";

/**
 * VRF arena empirical pricing table — bundled mirror of
 * `engine/config/default.toml [[multiplier.empirical_cells]]`.
 *
 * Why this lives here:
 * The only authoritative price for a bet comes from the engine
 * (`POST /api/v1/trade/quote` returns the HMAC-signed multiplier
 * the contract will pay). The canvas, however, must show the *same*
 * number the user is going to be charged — otherwise cells render
 * one multiplier and quotes return another, and the bet either
 * disappoints (real < shown) or 400s with `QuoteMismatch` (drift > 1%).
 *
 * Rather than round-tripping `/quote-grid` per cell render (latency,
 * jitter, flicker on snake movement), we bundle the empirical table
 * the engine itself uses (`pricing.rs:213-243`) and reproduce the
 * same lookup client-side. The table is calibrated against the VRF
 * generator with `samples_per_cell = 4096`; it changes only when ops
 * re-runs `cargo run --release --bin calibrate_vrf` and bumps
 * `path_config_version`. When that happens, this file regenerates.
 *
 * Path lookup, tolerances, safety factor, target-p cap, EV+ guard,
 * and the floor/ceiling clamp all match the Rust implementation
 * 1-for-1. If the engine ever rejects a cell the lookup here marks
 * `disabledReason !== null`, so the canvas grays it out before the
 * user can click.
 *
 * Provenance — emitted by `bin/calibrate_vrf` and pasted into the
 * engine config; both are tracked together. Update procedure:
 *
 *   1. ops re-runs `bin/calibrate_vrf` after any tweak to
 *      vrf::path::PATH_CONFIG_VERSION / tick_ms / volatility_bps
 *      / bound_bps (see `arena_index.rs` constants).
 *   2. paste output under `[multiplier]` in `default.toml`.
 *   3. regenerate this file from the same TOML so the canvas keeps
 *      showing what the engine will quote.
 */

