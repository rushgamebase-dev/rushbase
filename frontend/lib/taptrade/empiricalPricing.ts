// === Pre-bucketed by durationMs for O(rows-per-duration) lookup
// instead of O(630). The catalog has 7 durations × 90 = 630 rows;
// per-duration buckets bring lookups under a microsecond.
const _BY_DURATION: Map<number, EmpiricalRow[]> = (() => {
  const m = new Map<number, EmpiricalRow[]>();
  for (const row of EMPIRICAL_CELLS) {
    const bucket = m.get(row[1]);
    if (bucket) bucket.push(row);
    else m.set(row[1], [row]);
  }
  return m;
})();

export interface EmpiricalLookup {
  pTouch: number;
  distanceBpsHit: number;
  offsetMsHit: number;
}

/**
 * Find the closest calibrated cell within ±DIST_TOL_BPS distance and
 * ±OFFSET_TOL_MS offset, requiring an exact duration match. Returns
 * `null` when no cell fits — caller MUST treat that as
 * `UNCALIBRATED` (disable cell, do not fall back to Bachelier).
 *
 * Mirror of `engine/src/touch/pricing.rs:213-237`.
 */
export function lookupEmpirical(
  distanceBps: number,
  durationMs: number,
  offsetMs: number,
): EmpiricalLookup | null {
  const bucket = _BY_DURATION.get(durationMs);
  if (!bucket) return null;
  let bestScore = Number.POSITIVE_INFINITY;
  let best: EmpiricalLookup | null = null;
  for (const [d, , off, p] of bucket) {
    const distDiff = Math.abs(d - distanceBps);
    const offDiff = Math.abs(off - offsetMs);
    if (distDiff > DIST_TOL_BPS || offDiff > OFFSET_TOL_MS) continue;
    const score = distDiff + offDiff / 100;
    if (score < bestScore) {
      bestScore = score;
      best = { pTouch: p, distanceBpsHit: d, offsetMsHit: off };
    }
  }
  return best;
}

export type DisabledReason =
  | "UNCALIBRATED"
  | "EV_POSITIVE"
  | "INVALID_BAND"
  | "INVALID_WINDOW";

export interface EmpiricalQuote {
  /** Multiplier the cell will pay if the bet wins, in basis points. */
  multiplierBps: number;
  /** Human-readable multiplier (multiplierBps / 10_000). */
  multiplier: number;
  /** Padded p_touch (capped at TARGET_P_CAP), in bps. */
  impliedPTouchBps: number;
  /** Raw empirical p_touch hit (before safety factor / cap). */
  rawPTouch: number;
  /** Whether the cell hit the calibrated table. */
  fromEmpirical: boolean;
  /** Non-null = engine would refuse the cell. Canvas must gray it
   *  out and reject clicks. Order matches engine handler
   *  (`api/handlers/touch.rs:217-258`). */
  disabledReason: DisabledReason | null;
}

/** Returns the multiplier the engine would quote for this cell, or
 *  the reason it would refuse it. Pure function over the bundled
 *  table — zero network, deterministic, identical to what
 *  `/quote-grid` returns server-side. */
export function quoteCell(args: {
  distanceBps: number;
  durationMs: number;
  offsetMs: number;
  allowedDurationMs: ReadonlyArray<number>;
}): EmpiricalQuote {
  const { distanceBps, durationMs, offsetMs, allowedDurationMs } = args;

  // Window-duration sanity: engine refuses durations not in the
  // catalog regardless of the table.
  if (!allowedDurationMs.includes(durationMs)) {
    return makeDisabled("INVALID_WINDOW");
  }
  // Distance == 0: the band envelops the live price. Engine refuses
  // this hard regardless of table coverage; we mirror.
  if (distanceBps === 0) {
    return makeDisabled("EV_POSITIVE");
  }

  const hit = lookupEmpirical(
    distanceBps,
    durationMs,
    Math.max(0, offsetMs),
  );
  if (!hit) {
    // Stale calibration era — the bundled table was generated for
    // the legacy VRF generator, the live resolver is now arena_index.
    // Falling back to the floor multiplier (1.10×) keeps the cell
    // tappable; the engine still gets the final say at submit time
    // (any cell it can't price legitimately gets a 400, surfaced
    // by the toast). No EV+ exploit risk because the actual payout
    // is whatever the engine quotes, not this placeholder.
    return {
      multiplierBps: PRICING.MIN_MULT_BPS,
      multiplier: PRICING.MIN_MULT_BPS / 10_000,
      impliedPTouchBps: 0,
      rawPTouch: 0,
      fromEmpirical: false,
      disabledReason: null,
    };
  }

  // Pad and cap p_touch the same way `pricing.rs:232-237` does.
  const padded = Math.min(
    hit.pTouch * PRICING.EMPIRICAL_SAFETY_FACTOR,
    PRICING.TARGET_P_CAP,
  );
  const pTouch = Math.max(padded, PRICING.P_TOUCH_FLOOR);

  // EV+ guard. With the table calibrated against the live arena_index
  // (warm-up so the path's starting state matches real play),
  // p_touch * floor_multiplier > 1 means the cell would pay the
  // player a positive expected value at the 1.10× clamp. Mirror the
  // engine's refusal so the cell renders as disabled before the
  // user can click — better UX than a 400 toast on submit.
  const floorMult = PRICING.MIN_MULT_BPS / 10_000;
  if (pTouch * floorMult > 1.0) {
    return makeDisabled("EV_POSITIVE");
  }

  const edgeFactor = 1 - PRICING.HOUSE_EDGE_BPS / 10_000;
  const rawMult = edgeFactor / pTouch;
  const multBps = clamp(
    Math.round(rawMult * 10_000),
    PRICING.MIN_MULT_BPS,
    PRICING.MAX_MULT_BPS,
  );

  return {
    multiplierBps: multBps,
    multiplier: multBps / 10_000,
    impliedPTouchBps: Math.round(padded * 10_000),
    rawPTouch: hit.pTouch,
    fromEmpirical: true,
    disabledReason: null,
  };
}

function makeDisabled(reason: DisabledReason): EmpiricalQuote {
  return {
    multiplierBps: PRICING.MIN_MULT_BPS,
    multiplier: PRICING.MIN_MULT_BPS / 10_000,
    impliedPTouchBps: 0,
    rawPTouch: 0,
    fromEmpirical: false,
    disabledReason: reason,
  };
}

function clamp(value: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, value));
}
